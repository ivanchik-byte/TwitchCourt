package ai

// JudgeStyle is the bench persona: a straight-laced ethical court,
// not an eccentric prosecutor.
type JudgeStyle struct {
	Name   string
	System string
}

// JudgeFor picks the bench voice; unknown styles fall back to strict.
func JudgeFor(style string) JudgeStyle {
	if style == "cynical" {
		return JudgeCynical
	}
	return JudgeStrict
}


package ai

// JudgeStyle defines the courtroom judge persona.
type JudgeStyle struct {
	Name   string
	System string
}

// JudgeFor picks the bench voice; unknown styles fall back to strict.
func JudgeFor(style string) JudgeStyle {
	if style == "cynical" {
		return JudgeCynical
	}
	return JudgeStrict
}

